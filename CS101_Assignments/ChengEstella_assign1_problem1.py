# Given variables
price1 = 10
price2 = 26
price3 = 18
first_name = "Carlos"
last_name = "Alcaraz"
discount = .2

# Compute average price
average_price = (price1 + price2 + price3) / 3

# Calculate total price with discount
total_price = (price1 + price2 + price3) * (1 - discount)

# Output
print("Shopping cart for: " + first_name + " " + last_name)
print("Item prices: " + str(price1) + ", " + str(price2) + ", and " + str(price3))
print("Average Price: " + str(average_price))
print("Total Price with Discount: " + str(total_price))

